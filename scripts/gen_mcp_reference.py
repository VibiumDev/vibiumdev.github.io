#!/usr/bin/env python3
"""Generate the MCP tool reference from the vibium binaries.

Asks `vibium mcp` for its tool list over stdio (initialize, then tools/list;
no browser starts) from the latest npm release and the latest nightly, and
emits:

  docs/mcp/tools.md            every tool with its parameters
  site/public/mcp-tools.json   the raw tool schemas for agents

Tools present only in the nightly binary are marked "(nightly)".

Usage:
    python3 scripts/gen_mcp_reference.py
    python3 scripts/gen_mcp_reference.py --stable-bin PATH --nightly-bin PATH
"""
from __future__ import annotations

import argparse
import json
import subprocess
from pathlib import Path

from gen_command_reference import (
    REPO_ROOT,
    WORK_DIR,
    nightly_binary,
    npm_stable_binary,
    run,
)

TOOLS_PAGE = REPO_ROOT / "docs" / "mcp" / "tools.md"
TOOLS_JSON = REPO_ROOT / "site" / "public" / "mcp-tools.json"

REQUESTS = [
    {
        "jsonrpc": "2.0",
        "id": 1,
        "method": "initialize",
        "params": {
            "protocolVersion": "2025-06-18",
            "capabilities": {},
            "clientInfo": {"name": "vibium-docs", "version": "0"},
        },
    },
    {"jsonrpc": "2.0", "method": "notifications/initialized"},
    {"jsonrpc": "2.0", "id": 2, "method": "tools/list"},
]


def list_tools(binary: Path) -> list[dict]:
    stdin = "".join(json.dumps(r) + "\n" for r in REQUESTS)
    result = subprocess.run(
        [str(binary), "mcp"], input=stdin, capture_output=True, text=True, timeout=60
    )
    for line in result.stdout.splitlines():
        try:
            message = json.loads(line)
        except json.JSONDecodeError:
            continue
        if message.get("id") == 2 and "result" in message:
            return message["result"]["tools"]
    raise RuntimeError(f"{binary} mcp did not answer tools/list:\n{result.stderr}")


def one_line(text: str) -> str:
    return " ".join(text.split()).replace("|", "\\|")


def type_of(schema: dict) -> str:
    kind = schema.get("type", "any")
    if isinstance(kind, list):
        kind = " or ".join(kind)
    if kind == "array":
        kind = f"array of {type_of(schema.get('items', {}))}"
    if "enum" in schema:
        kind += ": " + ", ".join(f"`{v}`" for v in schema["enum"])
    return kind


def emit_tool(tool: dict, nightly_only: bool) -> list[str]:
    lines = [f"### `{tool['name']}`", ""]
    if nightly_only:
        lines += ["> **Nightly only.** Not in the latest release.", ""]
    lines += [" ".join(tool.get("description", "").split()), ""]
    schema = tool.get("inputSchema", {})
    properties = schema.get("properties", {})
    if not properties:
        lines += ["No parameters.", ""]
        return lines
    required = set(schema.get("required", []))
    lines += ["| Parameter | Type | Required | Description |", "|---|---|---|---|"]
    for name, prop in properties.items():
        lines.append(
            f"| `{name}` | {type_of(prop)} | {'yes' if name in required else 'no'} "
            f"| {one_line(prop.get('description', ''))} |"
        )
    lines.append("")
    return lines


def emit_page(tools: list[dict], stable_names: set[str], stable_version: str) -> str:
    parts = [
        "---",
        "title: MCP Tool Reference",
        "description: Every tool the Vibium MCP server exposes, with its parameters.",
        "tableOfContents:",
        "  maxHeadingLevel: 2",
        "---",
        "",
        "<!-- Generated by scripts/gen_mcp_reference.py from `vibium mcp`. Do not edit. -->",
        "",
        f"The Vibium MCP server exposes {len(tools)} tools. This page lists each",
        "one with its parameters, as reported by the server's own `tools/list`.",
        "The raw schemas are published as [`/mcp-tools.json`](/mcp-tools.json).",
        "",
        f"Tools marked **(nightly)** are not in the latest release ({stable_version});",
        "see [What's in Nightly](../nightly.md). To register the server, see",
        "[Client Setup](setup.md).",
        "",
        "## All tools",
        "",
        "| Tool | What it does |",
        "|---|---|",
    ]
    for tool in tools:
        badge = "" if tool["name"] in stable_names else " **(nightly)**"
        summary = one_line(tool.get("description", "")).split(". ")[0].rstrip(".")
        parts.append(f"| [`{tool['name']}`](#{tool['name']}){badge} | {summary} |")
    parts += ["", "## Parameters", ""]
    for tool in tools:
        parts += emit_tool(tool, tool["name"] not in stable_names)
    return "\n".join(parts).rstrip() + "\n"


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--stable-bin", type=Path)
    parser.add_argument("--nightly-bin", type=Path)
    parser.add_argument("--workdir", type=Path, default=WORK_DIR)
    args = parser.parse_args()

    args.workdir.mkdir(parents=True, exist_ok=True)
    stable_bin = args.stable_bin or npm_stable_binary(args.workdir)
    nightly_bin = args.nightly_bin or nightly_binary(args.workdir)[0]
    stable_version = run([str(stable_bin), "version"]).split()[-1].lstrip("v")

    tools = list_tools(nightly_bin)
    stable_names = {t["name"] for t in list_tools(stable_bin)}

    TOOLS_PAGE.write_text(emit_page(tools, stable_names, stable_version))
    data = {
        "stableVersion": stable_version,
        "tools": [
            {**tool, "nightlyOnly": tool["name"] not in stable_names} for tool in tools
        ],
    }
    TOOLS_JSON.write_text(json.dumps(data, indent=2, ensure_ascii=False) + "\n")
    new = sum(1 for t in tools if t["name"] not in stable_names)
    print(f"wrote docs/mcp/tools.md and mcp-tools.json ({len(tools)} tools, {new} nightly-only)")


if __name__ == "__main__":
    main()
